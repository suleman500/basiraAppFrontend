import '../../voice/services/voice_announcer.dart';

/// يستقبل رد الـAI (الجملة المُركّبة النهائية، بعد ما استقبل بيانات
/// buildObjectSummaries وصاغها لغويًا) وينطقه مباشرة عبر VoiceAnnouncer
/// الموجود أصلًا — بدون أي منطق قرار إضافي هون (نفس مبدأ الملف كله:
/// AI يصوغ، هالدالة بس تنطق اللي وصلها، بدون تدخل بالمحتوى).
///
/// ⚠️ هالدالة "محلية" بالكامل — كل اللي تعمله هو تنظيف بسيط ثم تمرير
/// النص لـVoiceAnnouncer.speakNow، اللي بدوره يستخدم حاليًا TtsAdapter
/// المحلي (FlutterTtsAdapter). لا علاقة لها بالإنترنت من قريب أو بعيد
/// — سواء كان النص جاي من AI عبر الإنترنت أو مكتوب يدويًا، النطق نفسه
/// يصير محليًا 100% بمحرك الهاتف. ميزة "صوت حقيقي عبر الإنترنت" (اللي
/// اتفقنا نبنيها لاحقًا) منفصلة تمامًا عن هالدالة — هي تغيير بمحرك
/// النطق نفسه (TtsAdapter بديل)، مو بهالدالة (اللي بتضل نفسها بدون أي
/// تعديل بغض النظر عن أي محرك نطق يُستخدَم لاحقًا).
///
/// بيعمل تنظيف بسيط قبل النطق لأن ردود نماذج الـAI أحيانًا بترجع بشكل
/// مو نظيف تمامًا (علامات اقتباس زايدة حوالين الجملة، تنسيق Markdown
/// زي **/*، مسافات/أسطر زايدة) — هذا شائع جدًا لو الرد جاي من نموذج
/// نصي عام مو مصمَّم خصيصًا لإرجاع نص خام بس.
Future<void> speakAiResponse(
    VoiceAnnouncer voice,
    String rawAiText,
    ) async {
  final cleaned = _cleanAiText(rawAiText);

  if (cleaned.isEmpty) return;

  await voice.speakNow(cleaned);
}

/// تنظيف بسيط لنص الـAI قبل النطق:
/// - إزالة علامات اقتباس تحيط بالجملة كاملة (شائع جدًا بردود النماذج)
/// - إزالة رموز Markdown الأساسية (**, *, #) لأنها بتتحوّل لكلام
///   غريب لو TTS حاول ينطقها حرفيًا
/// - توحيد المسافات/الأسطر المتعددة لمسافة وحدة
String _cleanAiText(String input) {
  var text = input.trim();

  // إزالة اقتباس محيط بالجملة كاملة (لو موجود) — مثلاً الرد جاي
  // بصيغة "الكرسي أمامك على يمينك" بعلامات اقتباس زايدة.
  if (text.length >= 2 &&
      ((text.startsWith('"') && text.endsWith('"')) ||
          (text.startsWith('\'') && text.endsWith('\'')))) {
    text = text.substring(1, text.length - 1).trim();
  }

  text = text
      .replaceAll('**', '')
      .replaceAll('*', '')
      .replaceAll('#', '')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();

  return text;
}