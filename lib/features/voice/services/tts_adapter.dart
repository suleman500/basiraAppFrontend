/// واجهة تجريدية (Adapter) لأي محرك نطق صوتي.
///
/// الهدف: عزل باقي التطبيق (VoiceAnnouncer وكل من يستدعيه) عن تفاصيل
/// أي مكتبة TTS محدَّدة. لو قررنا مستقبلًا نبدّل من flutter_tts لمحرك
/// آخر (مثل kitten_tts أو أي بديل)، كل اللي نسويه هو كتابة كلاس جديد
/// يطبّق هذي الواجهة — بدون أي تعديل على VoiceAnnouncer أو الشاشة.
///
/// هذا بالضبط الدرس اللي طلع من تجربتنا مع neural_tts ثم
/// kokoro_tts_flutter ثم الرجوع لـ flutter_tts — كل مرة كنا نضطر نعدّل
/// كود الشاشة نفسه. هذا التصميم يمنع تكرار المشكلة.
abstract class TtsAdapter {
  /// تهيئة المحرك (تحميل ملفات، فحص الأصوات المتاحة، إلخ).
  Future<void> init();


  /// يبدّل لغة النطق. يرجع true لو نجح التبديل فعليًا (مثلًا لو اللغة
  /// المطلوبة غير مدعومة بالجهاز، يرجع false وتضل اللغة القديمة فعّالة).
  Future<bool> setLanguage(String localeCode);

  /// ينطق نصًا. يقطع أي نطق سابق تلقائيًا.
  Future<void> speak(String text);

  /// يوقف أي نطق جارٍ فورًا.
  Future<void> stop();

  /// تحرير موارد المحرك عند إغلاق الشاشة.
  Future<void> dispose();
}